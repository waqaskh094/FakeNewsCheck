import { VERDICT } from '../lib/verdicts'

export default function ConfidenceMeter({ value, verdict, note }) {
  const pct = Math.max(0, Math.min(100, Math.round(value * 100)))
  return (
    <div className="min-w-0 flex-1">
      <div className="flex items-baseline justify-between">
        <span className="text-sm font-semibold text-slate-500 dark:text-ink-400">Confidence</span>
        <span className="text-3xl font-bold tabular-nums">{pct}%</span>
      </div>
      <div
        role="progressbar"
        aria-label="Confidence"
        aria-valuenow={pct}
        aria-valuemin={0}
        aria-valuemax={100}
        className="mt-1 h-2 overflow-hidden rounded-full bg-slate-200 dark:bg-ink-700"
      >
        {/* w-[N%] is generated by @source inline() in index.css */}
        <div className={`h-full rounded-full transition-all duration-700 w-[${pct}%] ${VERDICT[verdict].bar}`} />
      </div>
      <p className="mt-2 text-sm text-slate-500 dark:text-ink-400">{note}</p>
    </div>
  )
}
